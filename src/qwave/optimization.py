METHODS = ("A_fixed", "B_clean", "C_monte_carlo", "D_sensitivity")


def array_digest(*arrays: NDArray, context: str = "") -> str:
    """Exact dtype/shape/byte cache key; never round small parameter changes away."""
    digest = hashlib.sha256(context.encode())
    for values in arrays:
        array = np.ascontiguousarray(values)
        digest.update(str((array.dtype.str,array.shape)).encode())
        digest.update(array.tobytes())
    return digest.hexdigest()


class WorkBudgetExceeded(RuntimeError):
    """A complete new candidate would exceed the declared forward-work cap."""


class NumericalFailure(ValueError):
    """A solve failed a numerical screen and cannot become a feasible winner."""


class ScatteringCache:
    """Exact LRU cache with actual forward/response RHS and factorization counts.

    A regular energy sweep costs one RHS sweep. transmission_gradient performs
    a forward sweep plus another factorization with TWO RHS: three RHS-equivalent
    sweeps in total. Actual factorization counts are also saved, so this budget
    does not pretend a shared two-RHS factorization costs exactly twice as much.
    """

    def __init__(self, x: NDArray, energy: NDArray, arguments: dict[str,float], *,
                 context: str, entries: int = 128, tolerance: float = 1e-8) -> None:
        self.x, self.energy = np.array(x,copy=True), np.array(energy,copy=True)
        self.x.flags.writeable = self.energy.flags.writeable = False
        self.arguments = MappingProxyType(dict(arguments))
        self.context = array_digest(self.x,self.energy,context=context+json.dumps({"arguments":arguments,"tolerance":tolerance},sort_keys=True))
        self.entries, self.tolerance = entries, tolerance
        self.cache: OrderedDict[str, tuple[ScatteringResult, SpatialResponse | None]] = OrderedDict()
        self.work_limit: int | None = None
        self.forward_sweeps = self.response_rhs_sweeps = self.factorization_sweeps = 0
        self.hits = self.misses = self.evictions = 0
        self.max_conservation_error = self.max_response_residual = 0.

    @property
    def work(self) -> int:
        """RHS-equivalent sweeps consumed, independent of wall clock."""
        return self.forward_sweeps+self.response_rhs_sweeps

    def key(self, potential: NDArray) -> str:
        """Full potential plus grids, leads, mass, constants, code and numerical context."""
        value = np.asarray(potential)
        if np.iscomplexobj(value) or value.shape != self.x.shape or value.dtype.kind not in "iuf" or not np.all(np.isfinite(value)):
            raise ValueError("cached potential must be a finite real vector on the configured grid")
        return array_digest(np.asarray(value,dtype=float),context=self.context)

    def required_work(self, potentials: list[NDArray], *, response: bool = False) -> int:
        """Cost of missing distinct entries for an atomic candidate evaluation."""
        keys = {self.key(value) for value in potentials}
        return sum((3 if response else 1) for key in keys
                   if key not in self.cache or (response and self.cache[key][1] is None))

    def ensure_work(self, count: int) -> None:
        """Reject before starting a candidate whose complete metrics cannot fit."""
        if self.work_limit is not None and self.work+count > self.work_limit:
            raise WorkBudgetExceeded(f"work cap {self.work_limit}; consumed {self.work}, next candidate requires {count}")

    def solve(self, potential: NDArray, *, response: bool = False) -> tuple[ScatteringResult, SpatialResponse | None]:
        """Compute/retrieve a complete sweep and retain complex amplitudes unchanged."""
        key = self.key(potential)
        cached = self.cache.get(key)
        if cached is not None and (not response or cached[1] is not None):
            self.hits += 1
            self.cache.move_to_end(key)
            return cached
        self.ensure_work(3 if response else 1)
        self.misses += 1
        self.forward_sweeps += 1
        self.response_rhs_sweeps += 2 if response else 0
        self.factorization_sweeps += 2 if response else 1
        if response:
            derivative = transmission_gradient(self.x,potential,self.energy,**self.arguments)
            result = derivative.baseline
        else:
            derivative = None
            result = solve_scattering(self.x,potential,self.energy,**self.arguments)
        # A conserved probability sum cannot validate a phase, a linear solve,
        # or its derivative. These are numerical rejection screens, not a
        # continuum-accuracy claim. Use the configured lossless-solve tolerance
        # for the dimensionless residuals and absolute unit-flux amplitudes.
        if any(not np.all(np.isfinite(value)) for value in vars(result).values()
               if isinstance(value, np.ndarray)):
            raise NumericalFailure("nonfinite numerical scattering result")
        residual = float(np.max(result.relative_residual))
        if residual > self.tolerance:
            raise NumericalFailure(f"forward numerical residual screen failed: {residual:g}")
        error = float(np.max(result.conservation_error))
        self.max_conservation_error = max(self.max_conservation_error,error)
        if not np.isfinite(error) or error > self.tolerance:
            raise NumericalFailure(f"lossless-solver conservation screen failed: {error:g}")
        if derivative is not None:
            gradient = derivative.dt_dpotential_per_mev
            response_residual = derivative.max_response_solve_residual
            phase_difference = derivative.max_reassembled_t_difference
            if np.isfinite(response_residual):
                self.max_response_residual = max(self.max_response_residual, response_residual)
            if (gradient.shape != (len(self.energy), len(self.x)) or
                    not np.all(np.isfinite(gradient)) or
                    not np.isfinite(response_residual) or not 0 <= response_residual <= self.tolerance or
                    not np.isfinite(phase_difference) or not 0 <= phase_difference <= self.tolerance):
                raise NumericalFailure("complex response numerical screen failed: "
                    f"relative residual={response_residual:g}, reassembled t difference={phase_difference:g}")
        for value in vars(result).values():
            if isinstance(value,np.ndarray):
                value.flags.writeable = False
        if derivative is not None:
            derivative.dt_dpotential_per_mev.flags.writeable = False
        self.cache[key] = (result,derivative)
        self.cache.move_to_end(key)
        while len(self.cache) > self.entries:
            self.cache.popitem(last=False)
            self.evictions += 1
        return result,derivative

    def counters(self) -> dict[str, Any]:
        """Cost includes forward solves, response RHS, cache hits and numerical screens."""
        return {"forward_work":self.work,"forward_sweeps":self.forward_sweeps,
                "forward_energy_solves":self.forward_sweeps*len(self.energy),
                "response_rhs_sweeps":self.response_rhs_sweeps,
                "energy_rhs_solves":self.work*len(self.energy),
                "energy_factorizations":self.factorization_sweeps*len(self.energy),
                "cache_hits":self.hits,"cache_misses":self.misses,"cache_evictions":self.evictions,
                "max_conservation_error":self.max_conservation_error,
                "max_response_relative_residual":self.max_response_residual}


@dataclass(frozen=True)
class OptimizationProblem:
    """Fixed grids, covariance convention, incoming spectrum, target, and bounds."""

    config: OptimizeConfig
    device: PreparedChannel
    packet: GaussianPacket
    target_t: NDArray[np.complex128]
    importance_density: NDArray[np.float64]
    bounds: NDArray[np.float64]
    context: str
    setup_cost: dict[str,Any]

    @property
    def arguments(self) -> dict[str,float]:
        """Fixed leads and effective mass for every method and perturbation."""
        cfg = self.device.scatter
        return dict(effective_mass_ratio=cfg.effective_mass_ratio,left_lead_mev=cfg.left_lead_mev,
                    right_lead_mev=cfg.right_lead_mev)

    def cache(self) -> ScatteringCache:
        """Fresh method-local cache; no free solves from another method."""
        return ScatteringCache(self.device.x_nm,self.device.energy_mev,self.arguments,context=self.context,
                               entries=self.config.optimizer["cache_entries"],
                               tolerance=self.device.scatter.conservation_tolerance)

    def potential(self, u: NDArray) -> NDArray:
        """Gate bounds are constraints, not clipping of line-search trial potentials."""
        return self.device.background_mev+self.device.gates.shapes@u

    def packet_metrics(self, t: NDArray) -> dict[str,Any]:
        """Keep physical throughput separate from raw conditional target fidelity."""
        value = analyze_packet(self.device.energy_mev,self.packet.amplitude,t,self.target_t)
        return {"p_transmitted":value.p_transmitted,"raw_fidelity":value.raw_fidelity,
                "low_transmission":value.low_transmission}

    def clean_loss(self, metrics: dict[str,Any]) -> float:
        """Common B/C loss; undefined fidelity counts as zero ONLY in this loss."""
        alpha = self.config.objective["transmission_weight"]
        fidelity = metrics["raw_fidelity"] if metrics["raw_fidelity"] is not None else 0.
        return float(alpha*(1-metrics["p_transmitted"])+(1-alpha)*(1-fidelity))

    def sensitivity(self, response: SpatialResponse) -> tuple[float,float,NDArray]:
        """Lambda appears once: Var(eta)=lambda and phi excludes sqrt(lambda)."""
        derivative = response.dt_dpotential_per_mev@self.device.embedded_shapes
        variance = np.sum(self.device.modes.retained_eigenvalues*abs(derivative)**2,axis=1)
        raw = float(np.dot(self.packet.weights_mev*self.importance_density,variance))
        normalized = raw/self.config.model["disorder"]["sigma_mev"]**2
        return raw,normalized,derivative

    def residuals(self, u: NDArray, metrics: dict[str,Any], floor: float) -> tuple[dict[str,Any],NDArray]:
        """Nonnegative is feasible; save raw physical and solver-scaled residuals."""
        gates = self.device.gates.shapes@u
        slope = np.diff(gates)/np.diff(self.device.x_nm)
        bound = self.config.model["gates"]["total_abs_bound_mev"]
        max_slope = self.config.constraints["max_gate_gradient_mev_per_nm"]
        fidelity = metrics["raw_fidelity"]
        raw = {"transmission":float(metrics["p_transmitted"]-floor),
               "fidelity":float((fidelity if fidelity is not None else 0.)-self.config.constraints["minimum_clean_fidelity"]),
               "lower_gate_mev":(u-self.bounds[:,0]).tolist(),"upper_gate_mev":(self.bounds[:,1]-u).tolist(),
               "summed_gate_mev":float(bound-max(abs(gates))),
               "gradient_mev_per_nm":None if max_slope is None else float(max_slope-max(abs(slope)))}
        width = self.bounds[:,1]-self.bounds[:,0]
        scaled = [raw["transmission"],raw["fidelity"],*((u-self.bounds[:,0])/width),
                  *((self.bounds[:,1]-u)/width),raw["summed_gate_mev"]/bound]
        if max_slope is not None:
            scaled.append(raw["gradient_mev_per_nm"]/max_slope)
        return raw,np.asarray(scaled)


def prepare_problem(config: OptimizeConfig) -> OptimizationProblem:
    """Prepare shared science and target once, charging setup outside searches."""
    started = perf_counter()
    device = prepare_channel(config.model)
    packet = gaussian_packet(device.energy_mev,**config.packet,propagating_bounds_mev=config.propagating_bounds_mev())
    importance = abs(packet.amplitude)**2 if config.objective["weighting"] == "incoming_probability" else np.ones(len(device.energy_mev))
    importance = importance/np.dot(packet.weights_mev,importance)
    bounds = np.array([profile["bounds_mev"] for profile in config.model["gates"]["profiles"]],dtype=float)
    context = json.dumps({"config":config.to_dict(),"source":source_identity()["sha256"],
                          "constants":physical_constants(),"dtype":"float64/complex128"},sort_keys=True)
    arguments = dict(effective_mass_ratio=device.scatter.effective_mass_ratio,left_lead_mev=device.scatter.left_lead_mev,
                     right_lead_mev=device.scatter.right_lead_mev)
    cache = ScatteringCache(device.x_nm,device.energy_mev,arguments,context=context,
                            tolerance=device.scatter.conservation_tolerance)
    target,_ = cache.solve(sample_potential(device.x_nm,config.target_potential))
    probability = float(np.dot(packet.weights_mev,abs(packet.amplitude*target.t)**2))
    if probability < 1e-8:
        raise ValueError("declared target has negligible transmission; choose a resolvable target")
    return OptimizationProblem(config,device,packet,target.t,importance,bounds,context,
                               {**cache.counters(),"wall_seconds":perf_counter()-started,
                                "target_transmitted_probability":probability})


def disorder_draws(problem: OptimizationProblem, sample_count: int, seed: int) -> tuple[NDArray,NDArray,NDArray]:
    """PCG64 z, physical eta, and retained-KL potentials; no per-sample rescaling."""
    z = np.random.Generator(np.random.PCG64(seed)).standard_normal((sample_count,len(problem.device.modes.retained_eigenvalues)))
    eta = z*np.sqrt(problem.device.modes.retained_eigenvalues)
    return z,eta,eta@problem.device.embedded_shapes.T


class CandidateEvaluator:
    """Receives training draws only; every completed trial gets a full residual record."""

    def __init__(self, problem: OptimizationProblem, method: str, floor: float,
                 training_potentials: NDArray, *, phase: str = "search") -> None:
        if method not in METHODS:
            raise ValueError("unknown comparison method")
        self.problem,self.method,self.floor = problem,method,float(floor)
        raw = np.asarray(training_potentials)
        if np.iscomplexobj(raw) or raw.ndim!=2 or raw.shape[1]!=len(problem.device.x_nm) or not np.all(np.isfinite(raw)):
            raise ValueError("training potentials must be a finite real sample-by-position matrix")
        if method=="C_monte_carlo" and len(raw)==0:
            raise ValueError("Monte Carlo optimization requires training samples")
        self.training = np.array(raw,dtype=float,copy=True)
        self.training.flags.writeable = False
        self.candidate_context = array_digest(self.training,context=problem.context+method+str(self.floor))
        self.phase,self.start_index = phase,-1
        self.cache = problem.cache()
        self.records: list[dict[str,Any]] = []
        self.data: list[dict[str,NDArray]] = []
        self.memo: dict[str,int] = {}
        self.started = perf_counter()
        self.current_u: NDArray | None = None

    def evaluate(self, u: NDArray) -> dict[str,Any]:
        """Record distinct candidates, including infeasible finite-difference probes."""
        raw_u = np.asarray(u)
        if np.iscomplexobj(raw_u) or raw_u.dtype.kind not in "iuf":
            raise ValueError("candidate gate vector must contain real numeric values")
        u = np.asarray(raw_u,dtype=float)
        if u.shape != (len(self.problem.bounds),) or not np.all(np.isfinite(u)):
            raise ValueError("candidate gate vector has wrong shape or nonfinite values")
        key = array_digest(u,context=self.candidate_context)
        if key in self.memo:
            return self.records[self.memo[key]]
        potential = self.problem.potential(u)
        potentials = [potential]
        if self.method == "C_monte_carlo":
            potentials.extend(potential+draw for draw in self.training)
        # Reserve a whole candidate conservatively; eviction cannot cause a
        # partially scored candidate to consume the remaining budget.
        required = 3 if self.method == "D_sensitivity" else len(potentials)
        self.cache.ensure_work(required)
        self.current_u = u.copy()
        start = perf_counter()
        actual,response = self.cache.solve(potential,response=self.method == "D_sensitivity")
        metrics = self.problem.packet_metrics(actual.t)
        loss = self.problem.clean_loss(metrics)
        raw_j = normalized_j = None
        data = {"u_mev":u.copy(),"clean_t":actual.t.copy()}
        if self.method == "C_monte_carlo":
            train_t = np.stack([self.cache.solve(value)[0].t for value in potentials[1:]])
            loss = float(np.mean([self.problem.clean_loss(self.problem.packet_metrics(t)) for t in train_t]))
            data["training_t"] = train_t
        elif self.method == "D_sensitivity":
            assert response is not None
            raw_j,normalized_j,derivative = self.problem.sensitivity(response)
            data["dt_deta"] = derivative
            loss = normalized_j if self.problem.config.objective["normalization"] == "nominal_variance" else raw_j
        residuals,scaled = self.problem.residuals(u,metrics,self.floor)
        if not np.isfinite(loss) or not np.all(np.isfinite(scaled)):
            raise NumericalFailure("nonfinite numerical objective or constraint residual")
        feasible = bool(np.min(scaled) >= -self.problem.config.constraints["feasibility_tolerance"]
                        and metrics["raw_fidelity"] is not None and not metrics["low_transmission"])
        row = {"candidate_id":len(self.records),"method":self.method,"phase":self.phase,"start_index":self.start_index,
               "minimum_clean_transmission":self.floor,"u_mev":u.tolist(),"objective":loss,
               "clean_loss":self.problem.clean_loss(metrics),"sensitivity_J":raw_j,
               "sensitivity_J_per_mev2":normalized_j,**metrics,"constraint_residuals":residuals,
               "scaled_constraint_residuals":scaled.tolist(),"minimum_scaled_residual":float(min(scaled)),
               "feasible":feasible,"work_at_evaluation":self.cache.work,
               "evaluation_wall_seconds":perf_counter()-start,"elapsed_wall_seconds":perf_counter()-self.started}
        self.memo[key] = len(self.records)
        self.records.append(row)
        self.data.append(data)
        return row

    def vector(self, u: NDArray) -> NDArray:
        """Objective and clean constraints share the identical cached amplitude."""
        row = self.evaluate(u)
        return np.array([row["objective"],row["p_transmitted"],row["raw_fidelity"] or 0.])


def bounded_jacobian(function: Callable[[NDArray],NDArray], u: NDArray, bounds: NDArray,
                     step: float) -> NDArray:
    """Second-order real central/one-sided differences in physical meV coordinates.

    Boundaries use three-point formulas within individual bounds. Other constraints
    may be violated by probes. abs/conjugation preclude complex-step differentiation.
    """
    columns = []
    for j in range(len(u)):
        direction = np.zeros(len(u)); direction[j] = step
        represented = ((u+direction)[j]-(u-direction)[j])/(2*step)
        if not np.isfinite(represented) or abs(represented-1) > .01:
            raise NumericalFailure("gate finite-difference step is not representable to 1% accuracy")
        if u[j]-step >= bounds[j,0] and u[j]+step <= bounds[j,1]:
            column = (function(u+direction)-function(u-direction))/(2*step)
        elif u[j]+2*step <= bounds[j,1]:
            column = (-3*function(u)+4*function(u+direction)-function(u+2*direction))/(2*step)
        else:
            column = (3*function(u)-4*function(u-direction)+function(u-2*direction))/(2*step)
        columns.append(column)
    return np.column_stack(columns)


def gate_jacobian(evaluator: CandidateEvaluator, u: NDArray, step: float) -> NDArray:
    """Check represented physical potential directions before differencing objectives.

    A small coefficient can be representable while its contribution disappears
    under a nonzero background. Testing coefficient arithmetic alone misses this.
    """
    problem = evaluator.problem
    base = problem.potential(u)
    for j,shape in enumerate(problem.device.gates.shapes.T):
        delta = np.zeros(len(u));delta[j] = step
        positive = (problem.potential(u+delta)-base)/step
        negative = (base-problem.potential(u-delta))/step
        error = max(np.max(abs(positive-shape)),np.max(abs(negative-shape)))/max(abs(shape))
        if not np.isfinite(error) or error > .01:
            raise NumericalFailure("gate-potential perturbation is not representable to 1% accuracy")
    return bounded_jacobian(evaluator.vector,u,problem.bounds,step)


def gate_step_check(evaluator: CandidateEvaluator, u: NDArray) -> dict[str,Any]:
    """Selected/half-step gradient comparison before search; tiny steps are not tuning data."""
    settings = evaluator.problem.config.diagnostics
    steps = settings["gate_steps_mev"]
    jacobians: list[NDArray | None] = []
    unresolved = []
    for h in steps:
        try:
            jacobians.append(gate_jacobian(evaluator,u,h))
            unresolved.append(None)
        except NumericalFailure as error:
            jacobians.append(None)
            unresolved.append(str(error))
    selected = steps.index(evaluator.problem.config.optimizer["gate_step_mev"])
    reference = steps.index(evaluator.problem.config.optimizer["gate_step_mev"]/2)
    usable = jacobians[selected] is not None and jacobians[reference] is not None
    difference = abs(jacobians[selected]-jacobians[reference]) if usable else None
    allowance = settings["gradient_atol"]+settings["gradient_rtol"]*abs(jacobians[reference]) if usable else None
    errors = [float(np.max(abs(value-jacobians[reference]))) if value is not None and jacobians[reference] is not None
              else None for value in jacobians]
    growth = (errors[-1] is None or errors[-1] > 4*max(errors[selected],np.finfo(float).eps)) if usable else False
    return {"passed":bool(usable and np.all(difference <= allowance)),"steps_mev":steps,
            "jacobians_objective_P_F_per_mev":[None if value is None else value.tolist() for value in jacobians],
            "unresolved_step_errors":unresolved,
            "max_selected_half_step_difference":float(np.max(difference)) if usable else None,
            "max_errors_relative_to_half_step":errors,
            "tiny_step_growth":bool(growth),
            "reference_note":"half-step stability screen, not a rigorous gradient error bound"}


def initializations(problem: OptimizationProblem) -> NDArray:
    """Same configured start plus seeded uniform box starts for every method."""
    settings = problem.config.optimizer
    rng = np.random.Generator(np.random.PCG64(settings["initialization_seed"]))
    starts = rng.uniform(problem.bounds[:,0],problem.bounds[:,1],size=(settings["starts"],len(problem.bounds)))
    starts[0] = problem.device.gates.amplitudes_mev
    return starts


def run_multistart(evaluator: CandidateEvaluator, starts: NDArray, *, scale: float,
                   preflight_passed: bool) -> dict[str,Any]:
    """Explicit SLSQP constraints and equal per-start work caps; best feasible observed trial.

    Selection includes recorded derivative probes. Solver success is independent
    of feasibility; no point is selected if every evaluated candidate is infeasible.
    """
    started = perf_counter()
    problem = evaluator.problem
    cfg = problem.config.optimizer
    runs: list[dict[str,Any]] = []
    if evaluator.method == "A_fixed":
        evaluator.evaluate(starts[0])
    elif preflight_passed:
        lower,width = problem.bounds[:,0],problem.bounds[:,1]-problem.bounds[:,0]
        shape = problem.device.gates.shapes
        bound = problem.config.model["gates"]["total_abs_bound_mev"]
        matrix = np.vstack((shape,-shape))/bound
        slope = problem.config.constraints["max_gate_gradient_mev_per_nm"]
        if slope is not None:
            gradient = np.diff(shape,axis=0)/np.diff(problem.device.x_nm)[:,None]/slope
            matrix = np.vstack((matrix,gradient,-gradient))
        allocations = np.full(len(starts),cfg["forward_work_budget"]//len(starts),dtype=int)
        allocations[:cfg["forward_work_budget"]%len(starts)] += 1
        for index,(initial,allocation) in enumerate(zip(starts,allocations)):
            evaluator.start_index = index
            before = evaluator.cache.work
            evaluator.cache.work_limit = before+int(allocation)
            jac_cache: dict[str,NDArray] = {}
            def jac(v: NDArray) -> NDArray:
                key = array_digest(v)
                if key not in jac_cache:
                    jac_cache[key] = gate_jacobian(evaluator,lower+width*v,cfg["gate_step_mev"])*width
                return jac_cache[key]
            def constraints(v: NDArray) -> NDArray:
                values = evaluator.vector(lower+width*v)
                return values[1:]-[evaluator.floor,problem.config.constraints["minimum_clean_fidelity"]]
            try:
                result = minimize(lambda v:evaluator.vector(lower+width*v)[0]/scale,(initial-lower)/width,
                    method="SLSQP",jac=lambda v:jac(v)[0]/scale,bounds=[(0.,1.)]*len(lower),
                    constraints=[{"type":"ineq","fun":constraints,"jac":lambda v:jac(v)[1:]},
                        {"type":"ineq","fun":lambda v:1-matrix@(lower+width*v),"jac":lambda v:-matrix*width}],
                    options={"maxiter":cfg["maxiter"],"ftol":cfg["ftol"],"disp":False})
                runs.append({"start_index":index,"status":int(result.status),"success":bool(result.success),
                             "message":str(result.message),"iterations":int(result.nit),
                             "returned_u_mev":(lower+width*result.x).tolist()})
            except (WorkBudgetExceeded,NumericalFailure) as error:
                runs.append({"start_index":index,"status":None,"success":False,"message":str(error),
                             "stop_reason":"work_budget" if isinstance(error,WorkBudgetExceeded) else "numerical_failure"})
                if isinstance(error,NumericalFailure):
                    runs[-1]["failed_candidate"] = {"u_mev":None if evaluator.current_u is None else evaluator.current_u.tolist(),
                        "objective":None,"constraint_residuals":None,"reason":str(error)}
            runs[-1].update(allocated_forward_work=int(allocation),used_forward_work=evaluator.cache.work-before)
    else:
        runs.append({"success":False,"stop_reason":"gradient_preflight_failed",
                     "message":"Search skipped; no candidate may be presented as an optimized design."})
    feasible = [row for row in evaluator.records if row["feasible"]]
    selected = min(feasible,key=lambda row:row["objective"]) if feasible else None
    return {"method":evaluator.method,"minimum_clean_transmission":evaluator.floor,"runs":runs,
            "preflight_passed":preflight_passed,"selected_candidate_id":None if selected is None else selected["candidate_id"],
            "selected":selected,"feasible_candidate_count":len(feasible),"evaluated_candidates":len(evaluator.records),
            "status":"feasible_observed" if selected is not None else "no_feasible_candidate",
            "objective_divisor_for_solver":scale,"budget_forward_work":0 if evaluator.method=="A_fixed" else cfg["forward_work_budget"],
            "cost":{**evaluator.cache.counters(),"wall_seconds":perf_counter()-started}}
